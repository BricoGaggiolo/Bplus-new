create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  title text not null, provider text, description text,
  mandatory boolean not null default false,
  status text not null default 'planned' check (status in ('planned','active','completed','cancelled')),
  created_at timestamptz not null default now()
);
create table if not exists public.course_sessions (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses(id) on delete cascade,
  session_date date not null, start_time time, end_time time
);
create table if not exists public.course_participants (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.course_sessions(id) on delete cascade,
  employee_id bigint not null references public.employees(id) on delete cascade,
  status text not null default 'invited' check (status in ('invited','confirmed','absent')),
  unique(session_id, employee_id)
);
create table if not exists public.shift_weeks (
  id bigint generated by default as identity primary key,
  week_start date not null,
  location_id bigint references public.locations(id) on delete cascade,
  status text not null default 'draft' check (status in ('draft','published')),
  snapshot jsonb not null default '{}'::jsonb,
  published_at timestamptz,
