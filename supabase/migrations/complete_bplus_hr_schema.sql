create table if not exists public.store_hours (
  id bigint generated by default as identity primary key,
  location_id bigint not null references public.locations(id) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  is_closed boolean not null default false,
  schedule_type text not null default 'continuous' check (schedule_type in ('continuous','split')),
  open_time time, close_time time,
  morning_open time, morning_close time,
  afternoon_open time, afternoon_close time,
  min_staff integer not null default 0 check (min_staff >= 0),
  min_opening integer not null default 0 check (min_opening >= 0),
  min_closing integer not null default 0 check (min_closing >= 0),
  min_lunch integer check (min_lunch is null or min_lunch >= 0),
  unique(location_id, day_of_week)
);

create table if not exists public.store_date_overrides (
  id bigint generated by default as identity primary key,
  location_id bigint not null references public.locations(id) on delete cascade,
  override_date date not null,
  is_closed boolean not null default false,
  schedule_type text not null default 'continuous' check (schedule_type in ('continuous','split')),
  open_time time, close_time time,
  morning_open time, morning_close time,
  afternoon_open time, afternoon_close time,
  min_staff integer not null default 0 check (min_staff >= 0),
  min_opening integer not null default 0 check (min_opening >= 0),
  min_closing integer not null default 0 check (min_closing >= 0),
  min_lunch integer check (min_lunch is null or min_lunch >= 0),
  unique(location_id, override_date)
);

